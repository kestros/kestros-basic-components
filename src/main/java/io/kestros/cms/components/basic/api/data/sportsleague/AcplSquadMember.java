package io.kestros.cms.components.basic.api.data.sportsleague;

/**
 * A squad-list row for the featured team.
 */
public class AcplSquadMember {

  private int num;
  private String name;
  private String pos;
  private int age;

  public int getNum() {
    return num;
  }

  public String getName() {
    return name;
  }

  public String getPos() {
    return pos;
  }

  public int getAge() {
    return age;
  }
}
